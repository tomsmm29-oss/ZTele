@zedub.zed_cmd(pattern="^[.,](سبه|نيكه)\s?(\d+)?$")
async def raid_cmd(event):
    reply = await event.get_reply_message()
    if not reply:
        return await edit_or_reply(event, "**•❐• عـذراً .. يجـب الـرد عـلى المـسـتهـدف أولاً**")

    cmd_type = event.pattern_match.group(1)
    pool = list(SEBA_LIST) if cmd_type == "سبه" else list(NEKA_LIST)

    count_match = event.pattern_match.group(2)
    count = int(count_match) if count_match else 20
    
    if count > 60:
        count = 60

    await event.delete()
    random.shuffle(pool)
    
    for i in range(count):
        try:
            msg = pool[i % len(pool)]
            await event.client.send_message(
                event.chat_id, 
                msg, 
                reply_to=reply.id
            )
            
            if (i + 1) % 5 == 0:
                await asyncio.sleep(0.1)
                
        except Exception:
            break